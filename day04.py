# strip, lstrip, rstrip methods
a='coding is simple'
print(a.strip())
print(a.lstrip())
print(a.rstrip())
#replace
a='python is simple,python is easy,python is allrounder'
b=a.replace('python','java')
print(a)
print(b)
#upper, lower, swapcase, title, capitalize
a='PYTHON is HArd'
print(a.lower())
print(a.upper())
print(a.swapcase())
print(a.title())
print(a.capitalize())
#count, startswith, endswith
a='abacad'
b=a.startswith('a')
c=a.startswith('ad')
d=a.endswith('d')
e=a.endswith('de')
f=a.count('a')
g=a.count('ad')
print(b)
print(c)
print(d)
print(e)
print(f)
print(g)


